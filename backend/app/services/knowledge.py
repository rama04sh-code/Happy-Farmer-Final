SUPPORTED_CROPS = {"tomato": "الطماطم", "potato": "البطاطا", "pepper": "الفلفل"}

_ALIASES = {
    "tomato": ["طماطم", "بندوره", "tomato"],
    "potato": ["بطاطا", "بطاطس", "potato"],
    "pepper": ["فلفل", "pepper"],
}


def normalize(text: str) -> str:
    t = text.strip().lower()
    for a, b in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ة", "ه"), ("ى", "ي")):
        t = t.replace(a, b)
    return t


def canonical_crop(name: str) -> str | None:
    n = normalize(name)
    for key, aliases in _ALIASES.items():
        if any(normalize(a) in n for a in aliases):
            return key
    return None


